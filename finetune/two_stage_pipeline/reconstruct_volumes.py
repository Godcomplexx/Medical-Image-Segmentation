"""
Reconstruct FLAIR/T2 NIfTI volumes from the raw DICOM studies.

The two-stage dataset keeps only slice PNGs, but the anatomy-aware classifier needs
the 3D volume (to run SynthSeg and to index ``slice_{z}``). This rebuilds each
study's axial FLAIR/T2 volume from ``input_data`` using the existing, deterministic
converter (``create_t2_nifti`` with ``reorient=True``), so the reconstructed grid
matches the slices already generated by ``generate_images``.

CPU-only and independent of GPU training. Output goes to
``two_stage_full/anatomy/volumes/{study}/NIFTI/*.nii.gz`` and is idempotent.

    python -m finetune.two_stage_pipeline.reconstruct_volumes
"""
from __future__ import annotations

import argparse
import csv
import time
from pathlib import Path

from finetune.src.filetools.dicom_to_nifti_converter import create_t2_nifti


def _existing_volume(study_dir: Path) -> Path | None:
    nifti_dir = study_dir / "NIFTI"
    if not nifti_dir.is_dir():
        return None
    files = sorted(nifti_dir.glob("*.nii*"))
    return files[0] if files else None


def reconstruct_all(
    input_root: Path,
    output_root: Path,
    *,
    overwrite: bool = False,
) -> dict[str, object]:
    output_root.mkdir(parents=True, exist_ok=True)
    studies = sorted(p for p in input_root.iterdir() if p.is_dir())
    rows: list[dict[str, object]] = []
    ok = skipped = failed = 0

    for study in studies:
        target = output_root / study.name
        existing = _existing_volume(target)
        if existing is not None and not overwrite:
            skipped += 1
            rows.append({"study": study.name, "status": "skipped", "volume": str(existing)})
            continue
        start = time.time()
        try:
            create_t2_nifti(survey_path=study, postpr_path=output_root)
            volume = _existing_volume(target)
            if volume is None:
                raise RuntimeError("converter produced no NIfTI")
            ok += 1
            rows.append(
                {
                    "study": study.name,
                    "status": "ok",
                    "volume": str(volume),
                    "seconds": round(time.time() - start, 1),
                }
            )
        except Exception as exc:  # noqa: BLE001 - record and continue the batch
            failed += 1
            rows.append({"study": study.name, "status": "failed", "error": str(exc)[:200]})

    report = output_root / "reconstruction_report.csv"
    fieldnames = ["study", "status", "volume", "seconds", "error"]
    with report.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    return {
        "studies": len(studies),
        "ok": ok,
        "skipped": skipped,
        "failed": failed,
        "report": str(report),
    }


def main() -> None:
    project_root = Path(__file__).resolve().parents[2]
    default_input = project_root / "finetune" / "fileStorage" / "input_data"
    default_output = (
        project_root / "finetune" / "fileStorage" / "two_stage_full" / "anatomy" / "volumes"
    )
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=default_input)
    parser.add_argument("--output", type=Path, default=default_output)
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()

    summary = reconstruct_all(args.input, args.output, overwrite=args.overwrite)
    print(summary)


if __name__ == "__main__":
    main()
