# -*- coding: utf-8 -*-
"""Конвертация labelmap (метки 1..4) в Slicer-сегментацию .seg.nrrd.

3D Slicer открывает .nii.gz как обычный том (или как LabelMap) — редактировать
его в Segment Editor можно только после ручной конвертации. Файл .seg.nrrd
загружается сразу как Segmentation node: имена I/P/S/U и цвета лежат внутри
файла, врач сразу правит кистью/ластиком.

    python -m review_tool.seg_nrrd "<папка исследования>"
    python -m review_tool.seg_nrrd study_seg.nii.gz -o study.seg.nrrd
"""
from __future__ import annotations
import argparse
import shutil
import tempfile
from pathlib import Path

import numpy as np
import nibabel as nib
import SimpleITK as sitk

# метка -> (имя сегмента, RGB 0..255); совпадает с MSLesions.ctbl
SEGMENTS = {
    1: ("I_инфратенториальный", (255, 60, 60)),
    2: ("P_перивентрикулярный", (60, 200, 60)),
    3: ("S_субкортикальный", (60, 120, 255)),
    4: ("U_юкстакортикальный", (240, 200, 40)),
}


def _sitk_from_nifti(data: np.ndarray, affine: np.ndarray) -> sitk.Image:
    """numpy (i,j,k) + RAS-affine nibabel -> sitk.Image в LPS (как ждёт ITK)."""
    img = sitk.GetImageFromArray(np.ascontiguousarray(
        np.transpose(data.astype(np.uint8), (2, 1, 0))))
    flip = np.diag([-1.0, -1.0, 1.0])                      # RAS -> LPS
    mat = flip @ affine[:3, :3]
    origin = flip @ affine[:3, 3]
    spacing = np.linalg.norm(mat, axis=0)
    spacing[spacing == 0] = 1.0
    direction = mat / spacing
    img.SetSpacing([float(s) for s in spacing])
    img.SetOrigin([float(o) for o in origin])
    img.SetDirection([float(v) for v in direction.flatten()])
    return img


def write_seg_nrrd(labels: np.ndarray, affine: np.ndarray, out_path: Path,
                   segments: dict[int, tuple[str, tuple[int, int, int]]] = SEGMENTS) -> Path:
    """Сохранить labelmap как .seg.nrrd, редактируемый в Segment Editor."""
    labels = np.asarray(labels).astype(np.uint8)
    img = _sitk_from_nifti(labels, affine)
    img.SetMetaData("Segmentation_MasterRepresentation", "Binary labelmap")
    img.SetMetaData("Segmentation_ContainedRepresentationNames", "Binary labelmap|")
    img.SetMetaData("Segmentation_ConversionParameters", "")
    img.SetMetaData("Segmentation_ReferenceImageExtentOffset", "0 0 0")

    idx = 0
    for value, (name, rgb) in sorted(segments.items()):
        mask = labels == value
        if not mask.any():
            continue                                       # пустых сегментов не создаём
        ii, jj, kk = np.nonzero(mask)
        extent = f"{ii.min()} {ii.max()} {jj.min()} {jj.max()} {kk.min()} {kk.max()}"
        p = f"Segment{idx}_"
        img.SetMetaData(p + "ID", f"Segment_{value}")
        img.SetMetaData(p + "Name", name)
        img.SetMetaData(p + "NameAutoGenerated", "0")
        img.SetMetaData(p + "Color", " ".join(f"{c / 255.0:.6f}" for c in rgb))
        img.SetMetaData(p + "ColorAutoGenerated", "0")
        img.SetMetaData(p + "LabelValue", str(value))
        img.SetMetaData(p + "Layer", "0")
        img.SetMetaData(p + "Extent", extent)
        idx += 1

    out_path.parent.mkdir(parents=True, exist_ok=True)
    writer = sitk.ImageFileWriter()
    writer.UseCompressionOn()
    writer.KeepOriginalImageUIDOn()
    # ITK на Windows теряет не-ASCII символы в пути: пишем во временный файл и переносим
    with tempfile.TemporaryDirectory() as tmp:
        tmp_out = Path(tmp) / "segmentation.seg.nrrd"
        writer.SetFileName(str(tmp_out))
        writer.Execute(img)
        shutil.move(str(tmp_out), str(out_path))
    return out_path


def convert(seg_nii: Path, out_path: Path | None = None) -> Path:
    img = nib.load(str(seg_nii))
    name = seg_nii.name
    for suffix in (".nii.gz", ".nii"):
        if name.endswith(suffix):
            name = name[: -len(suffix)]
            break
    out = out_path or seg_nii.with_name(name + ".seg.nrrd")
    return write_seg_nrrd(np.asarray(img.get_fdata()), img.affine, out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("path", type=Path,
                    help="*_seg.nii.gz либо папка исследования (или папка с папками)")
    ap.add_argument("-o", "--output", type=Path, default=None)
    args = ap.parse_args()

    if args.path.is_file():
        targets = [args.path]
    else:
        targets = sorted(args.path.glob("*_seg.nii.gz")) or \
                  sorted(args.path.glob("*/*_seg.nii.gz"))
    if not targets:
        raise SystemExit(f"Не найдено *_seg.nii.gz в {args.path}")
    for seg in targets:
        out = convert(seg, args.output if len(targets) == 1 else None)
        print(f"[ok] {out}")


if __name__ == "__main__":
    main()
